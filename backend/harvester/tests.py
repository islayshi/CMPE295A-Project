@pytest.mark.django_db
def test_archive_old_predictions():
    """
    Verifies that archive_old_predictions correctly deletes PredictionPolygon
    records older than 30 days and leaves newer records intact.
    """
    from harvester.tasks import archive_old_predictions
    from predictions.models import PredictionPolygon
    from grid.models import BayAreaGrid
    from django.contrib.gis.geos import Polygon, Point
    from datetime import datetime, timedelta, timezone

    # Seed grid
    cell_polygon = Polygon((
        (-122.2, 37.0), (-122.1, 37.0), (-122.1, 37.1), (-122.2, 37.1), (-122.2, 37.0)
    ), srid=4326)
    grid = BayAreaGrid.objects.create(
        id=2001, geometry=cell_polygon,
        centroid=Point(-122.15, 37.05, srid=4326),
        row=0, col=0,
    )

    now = datetime.now(timezone.utc)
    # Create 31 days old prediction (should be deleted)
    PredictionPolygon.objects.create(
        grid_id=2001, timestamp=now - timedelta(days=31),
        source_model="mock", fire_probability=0.5
    )
    # Create 29 days old prediction (should be kept)
    PredictionPolygon.objects.create(
        grid_id=2001, timestamp=now - timedelta(days=29),
        source_model="mock", fire_probability=0.5
    )
    # Create current prediction (should be kept)
    PredictionPolygon.objects.create(
        grid_id=2001, timestamp=now,
        source_model="mock", fire_probability=0.5
    )

    assert PredictionPolygon.objects.count() == 3

    result = archive_old_predictions.apply()
    
    assert result.result["status"] == "success"
    assert result.result["deleted_count"] == 1
    assert PredictionPolygon.objects.count() == 2
